/** Every screen has a URL. Builders keep links consistent. */
const enc = encodeURIComponent;
export const homePath = () => "/";
export type IdentifyMode = "type" | "scan" | "connect";
export const newUnitPath = (mode: IdentifyMode = "type") => `/units/new/${mode}`;
export const unitPath = (id: string) => `/units/${enc(id)}`;
export const connectPath = (unitId: string) => `/units/${enc(unitId)}/connect`;
export const describePath = (unitId: string) => `/units/${enc(unitId)}/troubleshoot`;
export const jobPath = (jobId: string) => `/jobs/${enc(jobId)}`;
export const jobPagePath = (jobId: string, assetId: string) => `/jobs/${enc(jobId)}/page/${enc(assetId)}`;
export const jobAskPath = (jobId: string) => `/jobs/${enc(jobId)}/ask`;
export const closeOutPath = (jobId: string) => `/jobs/${enc(jobId)}/close`;
export const proceduresPath = () => "/procedures";
export const procedurePath = (packId: string, taskId: string) => `/procedures/${enc(packId)}/${enc(taskId)}`;
export const printJobPath = (jobId: string) => `/print/job/${enc(jobId)}`;
export const printProcedurePath = (packId: string, taskId: string) => `/print/procedure/${enc(packId)}/${enc(taskId)}`;
export const manualHomePath = () => "/manual";
export const manualPackPath = (packId: string) => `/manual/${enc(packId)}`;
export const manualPath = (packId: string, sectionId: string) => `/manual/${enc(packId)}/section/${enc(sectionId)}`;
export const manualPagePath = (packId: string, sectionId: string, assetId: string) => `/manual/${enc(packId)}/section/${enc(sectionId)}/page/${enc(assetId)}`;
export const referencePath = (packId: string) => `/manual/${enc(packId)}/reference`;
export const referenceLookupPath = (packId: string, q: string) => `/manual/${enc(packId)}/reference/lookup/${enc(q)}`;
export const referenceTablePath = (packId: string, tableId: string) => `/manual/${enc(packId)}/reference/${enc(tableId)}`;
export const referenceRowPath = (packId: string, tableId: string, ord: number) => `/manual/${enc(packId)}/reference/${enc(tableId)}/${ord}`;
export const manualSearchPath = (packId: string, q: string) => `/manual/${enc(packId)}/search/${enc(q)}`;
export const learnPath = () => "/learn";
export const learnPracticePath = (packId: string) => `/learn/${enc(packId)}/practice`;
export const learnTreePath = (packId: string, treeId: string) => `/learn/${enc(packId)}/tree/${enc(treeId)}`;
export const reviewLessonPath = (lessonId: string) => `/review/${enc(lessonId)}`;
export const recordsPath = () => "/records";
export const reviewPath = () => "/review";
export const designPath = (screen?: string, state?: string) => (screen ? `/design/${enc(screen)}${state ? `/${enc(state)}` : ""}` : "/design");

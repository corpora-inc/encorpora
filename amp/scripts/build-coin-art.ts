import { readFileSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { coinKinds } from "../src/math/scene/art";

/**
 * Embeds the coin faces (`src/web/scene/coin-art/*.webp`, sources in the
 * README there) in `src/web/scene/coin-art.ts` as data URLs. Every renderer
 * (app, print, film player, headless film renders, server-side worksheets)
 * then draws a coin with no request and no loading gap.
 */
const dir = new URL("../src/web/scene/", import.meta.url);
const entries = coinKinds.map((coin) => {
  const bytes = readFileSync(new URL(`coin-art/${coin}.webp`, dir));
  return `  ${coin}: "data:image/webp;base64,${bytes.toString("base64")}",`;
});
const out = fileURLToPath(new URL("coin-art.ts", dir));
writeFileSync(
  out,
  `// Generated by scripts/build-coin-art.ts from coin-art/*.webp. Do not edit.
import type { CoinKind } from "../../math/scene/art";

/** The obverse of each coin as a data URL (sources: coin-art/README.md). */
export const coinFaceUrl: Record<CoinKind, string> = {
${entries.join("\n")}
};
`,
);
spawnSync("npx", ["prettier", "--write", out], { stdio: "inherit" });

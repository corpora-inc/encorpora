import { readFileSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { billValues } from "../src/math/scene/art";

/** Embed the original SVG sources for app, print and film, with no request. */
const dir = new URL("../src/web/scene/", import.meta.url);
const entries = billValues.map((value) => {
  const file = value === 1 ? "one" : "five";
  const bytes = readFileSync(new URL(`bill-art/${file}.svg`, dir));
  return `  ${value}: "data:image/svg+xml;base64,${bytes.toString("base64")}",`;
});
const out = fileURLToPath(new URL("bill-art.ts", dir));
writeFileSync(
  out,
  `// Generated by scripts/build-bill-art.ts from bill-art/*.svg. Do not edit.
import type { BillValue } from "../../math/scene/art";

/** Original AMP bill drawings (bill-art/README.md), embedded without a network request. */
export const billFaceUrl: Record<BillValue, string> = {
${entries.join("\n")}
};
`,
);
const result = spawnSync("npx", ["prettier", "--write", out], {
  stdio: "inherit",
});
if (result.error) throw result.error;
if (result.status !== 0) process.exit(result.status ?? 1);

def has(prompts, text):
    return any(text in p for p in prompts)


WORKSHEET_BREADTH = {
    'rule-pattern-term': lambda ps: all(has(ps, f'“{op}') for op in ('add', 'subtract', 'multiply by')),
    'rule-pattern-feature': lambda ps: True,
    'related-patterns-relationship': lambda ps: has(ps, 'how many times') and has(ps, 'The patterns continue'),
    'dependent-variable-equation': lambda ps: has(ps, 'always') and has(ps, 'car') and has(ps, 'printer'),
    'dependent-variable-value': lambda ps: has(ps, 'How many hours') and has(ps, 'How old') and has(ps, 'How many pages'),
    'compare-function-rates': lambda ps: all(has(ps, t) for t in ('the table', 'the graph', 'the equation', 'a description')),
    'linear-function-choice': lambda ps: has(ps, 'not linear') and has(ps, 'a linear function?'),
}


def worked_answer(lesson):
    """Recompute each worked example from its own prompt."""
    worked, template = lesson['workedExample'], lesson['templateIds'][0]
    prompt = worked['prompt']
    if template == 'rule-pattern-term':
        return str(solve_rule_term(prompt))
    if template == 'rule-pattern-feature':
        m = re.fullmatch(r'A number pattern starts at (\d+)\. Its rule is “add (\d+)\.” Is every number .+\?', prompt)
        terms = pattern_terms(int(m[1]), 'add', int(m[2]), 200)
        if feature_truth('Every number in the pattern is odd.', terms):
            return 'Every number is odd.'
        if feature_truth('Every number in the pattern is even.', terms):
            return 'Every number is even.'
        return 'The numbers alternate between odd and even.'
    if template == 'related-patterns-relationship':
        m = re.fullmatch(r'Pattern A starts at 0 and adds (\d+) each step\. Pattern B starts at 0 and adds (\d+) each step\. Each term of pattern B is how many times the matching term of pattern A\?', prompt)
        A, B = pattern_terms(0, 'add', int(m[1]), 10), pattern_terms(0, 'add', int(m[2]), 10)
        ratios = {Fraction(y, x) for x, y in zip(A, B) if x}
        require(len(ratios) == 1, 'Worked example multiplier')
        return str(ratios.pop())
    if template == 'dependent-variable-equation':
        m = re.search(r'After ([\d, and]+) hours it has traveled ([\d, and]+) miles', prompt)
        ts = [int(v) for v in re.findall(r'\d+', m[1])]
        ds = [int(v) for v in re.findall(r'\d+', m[2])]
        ks = {Fraction(d, t) for t, d in zip(ts, ds)}
        require(len(ks) == 1 and len(ts) == len(ds), 'Worked example rows')
        return f'd = {ks.pop()}t'
    if template == 'dependent-variable-value':
        return str(solve_value(prompt))
    if template == 'compare-function-rates':
        m = re.search(r'table x = ([\d, ]+) and y = ([\d, ]+)\. Function B\'s graph is a straight line through \((\d+), (\d+)\) and \((\d+), (\d+)\)', prompt)
        xs = [int(v) for v in m[1].split(', ')]
        ys = [int(v) for v in m[2].split(', ')]
        mA, bA = linear_from_points(list(zip(xs, ys)), 'A')
        mB, bB = linear_from_points([(int(m[3]), int(m[4])), (int(m[5]), int(m[6]))], 'B')
        rate, start = ('A' if mA > mB else 'B'), ('A' if bA > bB else 'B')
        return (f'Function {rate} has the greater rate of change and the greater initial value.' if rate == start
                else f'Function {rate} has the greater rate of change; function {start} has the greater initial value.')
    m = re.fullmatch(r'Which of these equations defines a function that is not linear: (.+)\?', prompt)
    rules = re.split(r', | or ', m[1])
    nonlinear = [r for r in rules if not is_linear(r)]
    require(len(rules) == 4 and len(nonlinear) == 1, 'Worked example needs exactly one nonlinear rule')
    return nonlinear[0]


def review_figures(figures):
    by_kind = {f['kind']: ET.fromstring(f['html']) for f in figures}
    require(set(by_kind) == {'pattern-rule-steps', 'related-patterns-graph', 'dependent-variable-graph', 'compare-functions-graph', 'linear-nonlinear-graph'}, 'Figure inventory')
    steps = by_kind['pattern-rule-steps']
    svg = next(e for e in steps.iter() if e.tag == 'svg')
    terms = [int(e.attrib['data-term']) for e in steps.iter() if 'data-term' in e.attrib]
    require(terms == pattern_terms(int(svg.attrib['data-start']), 'add', int(svg.attrib['data-step']), len(terms)), 'Rule steps must follow the rule')
    require(len([e for e in steps.iter() if 'data-arrow' in e.attrib]) == len(terms) - 1, 'One arrow per step')
    checked = 1
    for kind in ('related-patterns-graph', 'dependent-variable-graph', 'compare-functions-graph', 'linear-nonlinear-graph'):
        root = by_kind[kind]
        graph = next(e for e in root.iter() if e.tag == 'svg')
        x_max, y_max = int(graph.attrib['data-x-max']), int(graph.attrib['data-y-max'])
        for series in (e for e in graph.iter() if 'data-series' in e.attrib):
            pts = []
            for e in series.iter():
                if 'data-point' not in e.attrib:
                    continue
                x, y = map(int, e.attrib['data-point'].split(','))
                cx = float(e.attrib['cx']) if 'cx' in e.attrib else float(e.attrib['x']) + 5.5
                cy = float(e.attrib['cy']) if 'cy' in e.attrib else float(e.attrib['y']) + 5.5
                # Uniform scale on each axis: 0 at (62, 200), maxima at x 296 and y 30.
                require(abs(cx - (62 + x / x_max * 234)) < 1e-6 and abs(cy - (200 - y / y_max * 170)) < 1e-6, f'{kind}: point not at its coordinates')
                pts.append((x, y))
            lines = [e for e in series.iter() if e.tag == 'line']
            if lines:
                ln = lines[0]
                ends = [((float(ln.attrib[f'x{i}']) - 62) / 234 * x_max, (200 - float(ln.attrib[f'y{i}'])) / 170 * y_max) for i in (1, 2)]
                for x, y in pts:
                    (x1, y1), (x2, y2) = ends
                    require(abs((y - y1) * (x2 - x1) - (y2 - y1) * (x - x1)) < 1e-6 * max(1, x_max * y_max), f'{kind}: point off the drawn line')
            checked += 1
        cells = [tuple(map(int, e.attrib['data-cell'].split(','))) for e in root.iter() if 'data-cell' in e.attrib]
        if cells:
            row_text = [[(e.text or '').replace('−', '-') for e in tr if e.tag == 'td'] for tr in root.iter() if tr.tag == 'tr']
            require([int(v) for v in row_text[0]] == [c[0] for c in cells[:len(row_text[0])]] and [int(v) for v in row_text[1]] == [c[1] for c in cells[len(row_text[0]):]], f'{kind}: table text differs from its pairs')
    rel = [tuple(map(int, e.attrib['data-point'].split(','))) for e in by_kind['related-patterns-graph'].iter() if 'data-point' in e.attrib]
    require(rel == list(zip(pattern_terms(0, 'add', 2, 5), pattern_terms(0, 'add', 6, 5))), 'Related patterns figure must pair add 2 with add 6')
    car = [tuple(map(int, e.attrib['data-point'].split(','))) for e in by_kind['dependent-variable-graph'].iter() if 'data-point' in e.attrib]
    require(car == [(t, 65 * t) for t in range(1, 5)], 'Car figure must show d = 65t')
    curve = [tuple(map(int, e.attrib['data-point'].split(','))) for s in by_kind['linear-nonlinear-graph'].iter() if s.attrib.get('data-series') == '1' for e in s.iter() if 'data-point' in e.attrib]
    require(curve == [(x, x * x) for x in range(4)], 'Square points must show y = x²')
    return checked


def review_pattern_function_content(data=None):
    data = content(data)
    checked = 0
    for sheet in data['worksheets']:
        problems = sheet['problems']
        require(len(problems) == 12, 'Worksheet length')
        prompts = [p['public']['prompt'] for p in problems]
        keys = {json.dumps([p['public']['prompt'], p['public'].get('figure'), sorted(o['label'] for o in p['public']['response'].get('options', []))]) for p in problems}
        require(len(keys) == 12, 'Repeated worksheet problem')
        require(WORKSHEET_BREADTH[sheet['templateId']](prompts), 'Worksheet lacks required breadth: ' + sheet['templateId'])
        for p in problems:
            solved = solve_pattern_function(p['public'])
            require((p['answer'] == solved) if isinstance(solved, str) else Fraction(p['answer']) == solved, 'Worksheet answer mismatch')
            checked += review_problem(p)
    lessons = {lesson['id']: lesson for lesson in data['lessons']}
    require(set(lessons) == PATTERN_FUNCTION, 'Missing standalone lesson')
    for lesson in lessons.values():
        require(worked_answer(lesson) == lesson['workedExample']['answer'], 'Worked example answer: ' + lesson['id'])
        for text in lesson['workedExample']['steps'] + [p for s in lesson['sections'] for p in s['paragraphs']]:
            checked += arithmetic_claims(text)
    checked += review_figures(data['figures'])
    return {'worksheets': len(data['worksheets']), 'checkedClaims': checked, 'lessons': len(lessons), 'figures': len(data['figures'])}



"""Independent prompt- and figure-only checks for patterns, relationships and functions.

Pattern terms are generated by applying the stated rule step by step; features are
checked against 200 terms; equations are evaluated on every table row; rates come
from exact Fractions of displayed coordinates; linearity is decided by evaluating
each displayed rule with Fraction arithmetic. Nothing here calls the TypeScript
generator, and malformed or inconsistent givens are rejected.
"""

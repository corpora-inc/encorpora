def require(condition, message):
    if not condition:
        raise ValueError(message)


def integer(text):
    return int(text.replace('−', '-'))


def options(public):
    response = public['response']
    require(response['kind'] == 'choice', 'Expected a choice response')
    return [(o['id'], o['label']) for o in response['options']]


def only_true(public, truth):
    true = [oid for oid, label in options(public) if truth(label)]
    require(len(true) == 1, f'Expected exactly one true option, found {len(true)}: {public["prompt"]}')
    return true[0]


# ------------------------------------------------------------------ patterns
def pattern_terms(start, op, step, count):
    terms = [start]
    for _ in range(count - 1):
        last = terms[-1]
        terms.append(last + step if op == 'add' else last - step if op == 'subtract' else last * step)
    return terms


def solve_rule_term(prompt):
    m = re.fullmatch(r'A number pattern starts at (\d+)\. Its rule is “(add|subtract|multiply by) (\d+)\.” What is the (\d+)(st|nd|rd|th) number in the pattern\?', prompt)
    require(m is not None, 'Unrecognized rule-pattern prompt')
    k = int(m[4])
    require({1: 'st', 2: 'nd', 3: 'rd'}.get(k if k < 20 else k % 10, 'th') == m[5], 'Ordinal suffix')
    require(2 <= int(m[3]) and 4 <= k <= 12, 'Rule outside scope')
    terms = pattern_terms(int(m[1]), m[2].split()[0], int(m[3]), k)
    require(all(t >= 0 for t in terms), 'A whole-number pattern cannot go negative')
    return terms[-1]


def feature_truth(label, terms):
    if label == 'Every number in the pattern is odd.':
        return all(t % 2 for t in terms)
    if label == 'Every number in the pattern is even.':
        return all(t % 2 == 0 for t in terms)
    if label == 'The numbers in the pattern alternate between odd and even.':
        return all((a + b) % 2 == 1 for a, b in zip(terms, terms[1:]))
    m = re.fullmatch(r'Every number in the pattern is a multiple of (\d+)\.', label)
    if m:
        return all(t % int(m[1]) == 0 for t in terms)
    m = re.fullmatch(r'Every number in the pattern ends in the digit (\d)\.', label)
    require(m is not None, 'Unrecognized feature statement: ' + label)
    return all(str(t)[-1] == m[1] for t in terms)


def solve_rule_feature(public):
    m = re.fullmatch(r'A number pattern starts at (\d+)\. Its rule is “add (\d+)\.” Which statement about the pattern is true\?', public['prompt'])
    require(m is not None, 'Unrecognized feature prompt')
    terms = pattern_terms(int(m[1]), 'add', int(m[2]), 200)
    labels = [label for _, label in options(public)]
    require(len(labels) == 4 and len(set(labels)) == 4, 'Four distinct statements')
    return only_true(public, lambda label: feature_truth(label, terms))


# ------------------------------------------------------------------ figures
def display(public):
    figure = public.get('figure')
    require(figure and figure['kind'] == 'function-display', 'Missing function display')
    return figure


def check_graph(graph):
    require(graph['xMax'] % graph['xStep'] == 0 and graph['yMax'] % graph['yStep'] == 0, 'Ticks must divide the axes')
    require(graph['xMax'] // graph['xStep'] <= 12 and graph['yMax'] // graph['yStep'] <= 12, 'Too many grid steps')
    for s in graph['series']:
        for p in s['points']:
            require(0 <= p['x'] <= graph['xMax'] and 0 <= p['y'] <= graph['yMax'], 'Point off the grid')
            if 'line' in s:
                ln = s['line']
                require(Fraction(p['y']) == Fraction(ln['rise'], ln['run']) * p['x'] + ln['b'], 'Point not on its line')


def pairs(points):
    return [(p['x'], p['y']) for p in points]


# ------------------------------------------------------------------ related patterns
def solve_related(public):
    m = re.fullmatch(r'Pattern A starts at 0 and adds (\d+) each step\. Pattern B starts at 0 and adds (\d+) each step\. (.+)', public['prompt'])
    require(m is not None, 'Unrecognized related-patterns prompt')
    a, b, question = int(m[1]), int(m[2]), m[3]
    A, B = pattern_terms(0, 'add', a, 40), pattern_terms(0, 'add', b, 40)
    figure = display(public)
    rows = pairs(figure['table']['rows'])
    require(rows == list(zip(A, B))[:len(rows)] and len(rows) >= 3, 'Table must list matching terms in order')
    check_graph(figure['graph'])
    require(pairs(figure['graph']['series'][0]['points']) == rows, 'Graph must plot the table pairs')
    if question == 'Each term of pattern B is how many times the matching term of pattern A?':
        ratios = {Fraction(y, x) for x, y in zip(A, B) if x}
        require(len(ratios) == 1, 'No single multiplier')
        return ratios.pop()
    m = re.fullmatch(r'The patterns continue\. Which term of pattern B matches (\d+) in pattern A\?', question)
    require(m is not None, 'Unrecognized related-patterns question')
    target = int(m[1])
    require(target in A, 'The A-term must occur in pattern A')
    return B[A.index(target)]


# ------------------------------------------------------------------ dependent variables
EQUATION_FORMS = [
    (re.compile(r'([a-z]) = (\d+)([a-z])'), lambda k, v: k * v),
    (re.compile(r'([a-z]) = ([a-z]) \+ (\d+)'), lambda c, v: v + c),
    (re.compile(r'([a-z]) = ([a-z]) − (\d+)'), lambda c, v: v - c),
]


def equation_holds(label, y, x, rows):
    """True when the label states y as a function of x that every row obeys."""
    m = re.fullmatch(r'([a-z]) = (\d+)([a-z])', label)
    if m:
        left, k, right = m[1], int(m[2]), m[3]
        return left == y and right == x and all(r[1] == k * r[0] for r in rows)
    m = re.fullmatch(r'([a-z]) = ([a-z]) ([+−]) (\d+)', label)
    require(m is not None, 'Unrecognized equation option: ' + label)
    left, right, c = m[1], m[2], int(m[4]) * (1 if m[3] == '+' else -1)
    return left == y and right == x and all(r[1] == r[0] + c for r in rows)


def solve_equation_choice(public):
    # A context sentence, then one sentence naming both variables.
    m = re.fullmatch(r'.+\. ([^.]+\.) Which equation gives ([a-z]) in terms of ([a-z])\?', public['prompt'])
    require(m is not None, 'Unrecognized equation prompt')
    y, x = m[2], m[3]
    require(all(re.search(rf'\b{v}\b', m[1]) for v in (x, y)), 'The prompt must name both variables')
    figure = display(public)
    columns = figure['table']['columns']
    require(columns[0].startswith(x + ' (') and columns[1].startswith(y + ' ('), 'Columns must name the variables')
    rows = pairs(figure['table']['rows'])
    graph = figure['graph']
    check_graph(graph)
    require(graph['xLabel'] == columns[0] and graph['yLabel'] == columns[1], 'Axes must match the table')
    require(pairs(graph['series'][0]['points']) == rows, 'Graph must plot the table rows')
    # The context sentence fixes the kind of relationship; the rows must obey it.
    if 'always' in public['prompt']:
        c = int(re.search(r'always (\d+) ', public['prompt'])[1])
        require(all(r[1] - r[0] == c for r in rows), 'Rows contradict the stated difference')
    return only_true(public, lambda label: equation_holds(label, y, x, rows))


def solve_value(prompt):
    patterns = [
        (r'A printer prints (\d+) pages per minute, so p = (\d+)m for p pages in m minutes\. How many pages does it print in (\d+) minutes\?', 'forward'),
        (r'Sam earns (\d+) dollars per hour, so p = (\d+)h for p dollars earned in h hours\. How many dollars does Sam earn in (\d+) hours\?', 'forward'),
        (r'A car travels at a constant speed, so d = (\d+)t for d miles in t hours\. How many hours does it take to travel (\d+) miles\?', 'back'),
        (r'Each ticket costs (\d+) dollars, so c = (\d+)n for a cost of c dollars for n tickets\. How many tickets cost (\d+) dollars\?', 'back'),
    ]
    for pattern, direction in patterns:
        m = re.fullmatch(pattern, prompt)
        if not m:
            continue
        if direction == 'forward':
            require(m[1] == m[2], 'Rate and equation disagree')
            return int(m[2]) * int(m[3])
        groups = m.groups()
        require(len(groups) == 2 or groups[0] == groups[1], 'Rate and equation disagree')
        k, total = int(groups[0]), int(groups[-1])
        require(total % k == 0, 'Answer must be a whole number')
        return next(n for n in range(0, total + 1) if k * n == total)
    m = re.fullmatch(r'Mia is always (\d+) years older than her brother, so m = b \+ (\d+), where m is Mia\'s age and b is her brother\'s\. How old is her brother when Mia is (\d+)\?', prompt)
    require(m is not None and m[1] == m[2], 'Unrecognized value prompt')
    return next(b for b in range(0, int(m[3]) + 1) if b + int(m[2]) == int(m[3]))


# ------------------------------------------------------------------ compare functions
def linear_from_points(points, name):
    require(len(points) >= 2, 'Need two points')
    (x0, y0), (x1, y1) = points[0], points[1]
    m = Fraction(y1 - y0, x1 - x0)
    require(all(Fraction(y - y0) == m * (x - x0) for x, y in points), f'Function {name} is not linear')
    return m, y0 - m * x0


def equation_line(text):
    m = re.fullmatch(r'y = (−?\d*)x(?: ([+−]) (\d+))?', text)
    require(m is not None, 'Unrecognized linear equation: ' + text)
    slope = {'': 1, '−': -1}.get(m[1])
    slope = Fraction(slope if slope is not None else integer(m[1]))
    b = Fraction(0 if m[2] is None else int(m[3]) * (1 if m[2] == '+' else -1))
    return slope, b


def solve_compare(public):
    m = re.fullmatch(r'Function A is given by (.+?)\. Function B is given by (.+?)\. Which statement compares their rates of change and initial values correctly\?', public['prompt'])
    require(m is not None, 'Unrecognized comparison prompt')
    figure = display(public)
    if 'graph' in figure:
        check_graph(figure['graph'])
    functions = {}
    for name, source in (('A', m[1]), ('B', m[2])):
        if source == 'the table':
            table = figure['table']
            require(table.get('title') == f'Function {name}' and table['columns'] == ['x', 'y'], 'Table title')
            functions[name] = linear_from_points(pairs(table['rows']), name)
        elif source == 'the graph':
            series = [s for s in figure['graph']['series'] if s.get('label') == name]
            require(len(series) == 1, 'Graph series label')
            functions[name] = linear_from_points(pairs(series[0]['points']), name)
            ln = series[0]['line']
            require((Fraction(ln['rise'], ln['run']), Fraction(ln['b'])) == functions[name], 'Drawn line differs from its marked points')
        elif source.startswith('the equation '):
            functions[name] = equation_line(source[len('the equation '):])
        else:
            d = re.fullmatch(r'a description: its output is (−?\d+) when x = 0 and (increases|decreases) by (\d+) for each increase of 1 in x', source)
            require(d is not None, 'Unrecognized description')
            functions[name] = (Fraction(int(d[3]) * (1 if d[2] == 'increases' else -1)), Fraction(integer(d[1])))
    (mA, bA), (mB, bB) = functions['A'], functions['B']
    require(mA != mB and bA != bB, 'Comparison must have strict winners')
    rate, start = ('A' if mA > mB else 'B'), ('A' if bA > bB else 'B')

    def truth(label):
        one = re.fullmatch(r'Function ([AB]) has the greater rate of change and the greater initial value\.', label)
        if one:
            return (one[1], one[1]) == (rate, start)
        two = re.fullmatch(r'Function ([AB]) has the greater rate of change; function ([AB]) has the greater initial value\.', label)
        require(two is not None and two[1] != two[2], 'Unrecognized comparison statement')
        return (two[1], two[2]) == (rate, start)
    return only_true(public, truth)


def rule_function(text):
    """Exact evaluator for a displayed rule y = … in x (×, implicit products, ², /)."""
    require(text.startswith('y = '), 'Rule must define y')
    expr = text[4:].replace('−', '-').replace('²', '**2')
    expr = re.sub(r'(\d)\s*(x|\()', r'\1*\2', expr)
    expr = re.sub(r'x\s*\(', 'x*(', expr)
    tree = ast.parse(expr, mode='eval')

    def visit(node, x):
        if isinstance(node, ast.Constant) and type(node.value) is int:
            return Fraction(node.value)
        if isinstance(node, ast.Name) and node.id == 'x':
            return x
        if isinstance(node, ast.UnaryOp) and isinstance(node.op, ast.USub):
            return -visit(node.operand, x)
        if isinstance(node, ast.BinOp):
            a, b = visit(node.left, x), visit(node.right, x)
            op = type(node.op)
            if op is ast.Add: return a + b
            if op is ast.Sub: return a - b
            if op is ast.Mult: return a * b
            if op is ast.Div: return a / b
            if op is ast.Pow and b == 2: return a * a
        raise ValueError('Unsupported rule: ' + text)
    return lambda x: visit(tree.body, Fraction(x))


def is_linear(text):
    f = rule_function(text)
    xs = [1, 2, 3, 5, 8, 13]
    values = [f(x) for x in xs]
    slopes = {(values[i + 1] - values[i]) / (xs[i + 1] - xs[i]) for i in range(len(xs) - 1)}
    return len(slopes) == 1


def solve_linear_choice(public):
    prompt = public['prompt']
    require(prompt in ('Which equation defines a linear function?', 'Which equation defines a function that is not linear?'), 'Unrecognized linearity prompt')
    want = prompt == 'Which equation defines a linear function?'
    return only_true(public, lambda label: is_linear(label) == want)


def solve_pattern_function(public):
    template, prompt = public['templateId'], public['prompt']
    if template == 'rule-pattern-term':
        return Fraction(solve_rule_term(prompt))
    if template == 'rule-pattern-feature':
        return solve_rule_feature(public)
    if template == 'related-patterns-relationship':
        return Fraction(solve_related(public))
    if template == 'dependent-variable-equation':
        return solve_equation_choice(public)
    if template == 'dependent-variable-value':
        return Fraction(solve_value(prompt))
    if template == 'compare-function-rates':
        return solve_compare(public)
    if template == 'linear-function-choice':
        return solve_linear_choice(public)
    raise ValueError('Not a pattern/function template: ' + template)


# ------------------------------------------------------------------ explanations
def value(source):
    text = source.strip().replace('−', '-').replace('×', '*').replace('÷', '/')
    tree = ast.parse(text, mode='eval')

    def visit(node):
        if isinstance(node, ast.Constant) and type(node.value) is int:
            return Fraction(node.value)
        if isinstance(node, ast.UnaryOp) and isinstance(node.op, ast.USub):
            return -visit(node.operand)
        if isinstance(node, ast.BinOp):
            a, b = visit(node.left), visit(node.right)
            op = type(node.op)
            if op is ast.Add: return a + b
            if op is ast.Sub: return a - b
            if op is ast.Mult: return a * b
            if op is ast.Div: return a / b
        raise ValueError('Unsupported arithmetic claim: ' + source)
    return visit(tree.body)


TRAILING = re.compile(r'[−(\d][\d ()×÷+/−]*$')
LEADING = re.compile(r'^\s*[−(\d][\d ()×÷+/−]*')


def arithmetic_claims(step):
    """Check every 'arithmetic = arithmetic' pair; skip equations between variables."""
    checked = 0
    parts = step.split(' = ')
    for left, right in zip(parts, parts[1:]):
        a, b = TRAILING.search(left), LEADING.match(right)
        if a is None or b is None:
            continue
        lhs, rhs = a[0].strip(), b[0].strip().rstrip('(').strip()
        # A number glued to a letter is a coefficient (55t), not a value.
        end = right.index(rhs) + len(rhs) if rhs in right else len(right)
        if right[end:end + 1].isalpha() or (a.start() > 0 and left[a.start() - 1].isalnum()):
            continue
        if not re.search(r'\d', lhs) or not re.search(r'\d', rhs):
            continue
        try:
            lv, rv = value(lhs), value(rhs)
        except (SyntaxError, ValueError):
            continue
        require(lv == rv, 'False arithmetic in explanation: ' + step)
        checked += 1
    return checked


def review_problem(problem):
    public = problem['public']
    template = public['templateId']
    answer = solve_pattern_function(public)
    steps = problem['explanation']
    require(len(steps) >= 2 and problem['hint'], 'Explanation or hint missing')
    checked = sum(arithmetic_claims(step) for step in steps)
    if template in PATTERN_FUNCTION_NUMBER:
        require(checked >= 1, 'Explanation has no checked arithmetic')
        require(re.search(r'(?<![\d/−])' + str(answer) + r'(?![\d/])', steps[-1]), 'Final step must state the answer')
    else:
        labels = dict(options(public))
        feedback = problem.get('choiceFeedback') or {}
        require(set(feedback) == set(labels) - {answer}, 'Every wrong option needs feedback')
        joined = ' '.join(steps)
        if template in ('rule-pattern-feature', 'dependent-variable-equation', 'linear-function-choice'):
            key = labels[answer].split(' is ')[0] if template == 'rule-pattern-feature' else labels[answer]
            require(labels[answer] in joined or key in joined, 'Explanation must name the correct option')
    if template == 'dependent-variable-equation':
        rows = pairs(public['figure']['table']['rows'])
        require(all(f'{y} ' in steps[1] and f'{x}' in steps[1] for x, y in rows), 'Explanation must check every row')
    return checked


# ------------------------------------------------------------------ fixtures
def case(template, prompt, response=None, figure=None):
    public = {'templateId': template, 'prompt': prompt, 'response': response or {'kind': 'number'}}
    if figure is not None:
        public['figure'] = figure
    return public


def choice(*labels):
    return {'kind': 'choice', 'options': [{'id': f'option-{"abcd"[i]}', 'label': label} for i, label in enumerate(labels)]}


def table_graph(rows, xs, ys, columns=('Pattern A', 'Pattern B'), labels=('A', 'B'), line=None, title=None):
    points = [{'x': x, 'y': y} for x, y in rows]
    series = {'points': points}
    if line:
        series['line'] = line
    table = {'columns': list(columns), 'rows': points}
    if title:
        table['title'] = title
    return {'kind': 'function-display', 'table': table,
            'graph': {'xLabel': labels[0], 'yLabel': labels[1], 'xMax': xs[0], 'yMax': ys[0], 'xStep': xs[1], 'yStep': ys[1], 'series': [series]}}



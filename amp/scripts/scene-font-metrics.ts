/**
 * Regenerates src/math/scene/font-metrics.ts: advance widths (em) and em-box
 * extents for the two figure type styles, so scene layout is exact without a
 * DOM (server, print export, tests).
 *
 *   math  KaTeX_Main / KaTeX_Math: widths from KaTeX's own metric tables.
 *   text  the UI sans: the widest of Arial, Helvetica and system-ui as
 *         measured by Chromium, so an estimate never undercuts a real label.
 *
 *   npx tsx scripts/scene-font-metrics.ts
 */
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { pathToFileURL } from "node:url";
import { chromium } from "playwright";

const require = createRequire(import.meta.url);
const katexDir = dirname(require.resolve("katex/package.json"));
const data = (
  await import(pathToFileURL(join(katexDir, "src/fontMetricsData.js")).href)
).default as Record<string, Record<string, number[]>>;
const chars = [
  ...Array.from({ length: 95 }, (_, i) => String.fromCharCode(32 + i)),
  ..."−×÷·°′″≤≥≠≈√π…–—½¼¾",
];
// Advance widths; italic corrections are separate (the ink overhang of a
// slanted glyph, added after a label's last italic character).
const katexWidths = (font: string) =>
  Object.fromEntries(
    chars.flatMap((c) => {
      const m = data[font]?.[String(c.codePointAt(0))];
      return m ? [[c, Number(m[4]!.toFixed(4))]] : [];
    }),
  );

const browser = await chromium.launch();
const page = await browser.newPage();
const css = require.resolve("katex/dist/katex.min.css");
await page.setContent(
  `<html><head><link rel="stylesheet" href="${pathToFileURL(css).href}"></head><body><svg id="s" width="2000" height="200"></svg></body></html>`,
);
// tsx keeps function names with a helper the page does not define.
await page.evaluate("window.__name = (f) => f");
await page.evaluate(async () => {
  for (const f of ["KaTeX_Main", "KaTeX_Math"])
    await document.fonts.load(`100px ${f}`);
  await document.fonts.load(`italic 100px KaTeX_Math`);
});
const measured = await page.evaluate((chars) => {
  const svg = document.getElementById("s")!;
  const ns = "http://www.w3.org/2000/svg";
  const box = (
    family: string,
    text: string,
    weight = "400",
    style = "normal",
    size = 100,
  ) => {
    const t = document.createElementNS(ns, "text");
    t.setAttribute("x", "10");
    t.setAttribute("y", "150");
    t.setAttribute("font-size", String(size));
    t.setAttribute("font-family", family);
    t.setAttribute("font-weight", weight);
    t.setAttribute("font-style", style);
    t.setAttribute("xml:space", "preserve");
    t.textContent = text;
    svg.appendChild(t);
    const b = t.getBBox();
    const w = t.getComputedTextLength();
    t.remove();
    return {
      w: w / size,
      top: (150 - b.y) / size,
      bottom: (b.y + b.height - 150) / size,
    };
  };
  const families = ["Arial", "Helvetica", "system-ui"];
  const widths: Record<string, Record<string, number>> = {
    "400": {},
    "700": {},
  };
  for (const weight of ["400", "700"])
    for (const c of chars) {
      // A lone space has no box, so measure it between two letters. Small
      // sizes too: optical sizing makes UI fonts wider at 13–21 px.
      const width = Math.max(
        ...families.flatMap((f) =>
          [13, 14, 17, 21, 100].map((size) =>
            c === " "
              ? box(f, "x x", weight, "normal", size).w -
                2 * box(f, "x", weight, "normal", size).w
              : box(f, c.repeat(8), weight, "normal", size).w / 8,
          ),
        ),
      );
      widths[weight]![c] = Number(width.toFixed(4));
    }
  const ext = (f: string, style = "normal") => box(f, "Hg", "400", style);
  const sans = families.map((f) => ext(f));
  return {
    widths,
    sans: {
      ascent: Math.max(...sans.map((e) => e.top)),
      descent: Math.max(...sans.map((e) => e.bottom)),
    },
    math: (() => {
      const a = ext("KaTeX_Main"),
        b = ext("KaTeX_Math", "italic");
      return {
        ascent: Math.max(a.top, b.top),
        descent: Math.max(a.bottom, b.bottom),
      };
    })(),
  };
}, chars);
await browser.close();

const round = (n: number) => Number(n.toFixed(4));
const out = `// GENERATED by scripts/scene-font-metrics.ts. Do not edit.
/** Advance widths in em. \`main\`/\`italic\`: KaTeX_Main and KaTeX_Math. \`sans\`/
 * \`sansBold\`: the widest of Arial, Helvetica and system-ui. Extents are the
 * em box a browser reports for text (getBBox), above and below the baseline. */
export const fontMetrics = ${JSON.stringify(
  {
    main: katexWidths("Main-Regular"),
    italic: katexWidths("Math-Italic"),
    mainBold: katexWidths("Main-Bold"),
    italicBold: katexWidths("Math-BoldItalic"),
    italicCorrection: Object.fromEntries(
      chars.flatMap((c) => {
        const m = data["Math-BoldItalic"]?.[String(c.codePointAt(0))];
        return m ? [[c, Number(m[2]!.toFixed(4))]] : [];
      }),
    ),
    sans: measured.widths["400"],
    sansBold: measured.widths["700"],
    extent: {
      sans: {
        ascent: round(measured.sans.ascent),
        descent: round(measured.sans.descent),
      },
      math: {
        ascent: round(measured.math.ascent),
        descent: round(measured.math.descent),
      },
    },
  },
  null,
  1,
)} as const;
`;
writeFileSync(
  new URL("../src/math/scene/font-metrics.ts", import.meta.url),
  out,
);
console.log("wrote font-metrics.ts", measured.sans, measured.math);

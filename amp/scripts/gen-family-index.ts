/** Write src/families/index.ts: one export line per src/families/<id>.ts,
 * sorted by file name. `--check` exits 1 when the committed index is stale. */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { FAMILY_ID } from "../src/families/registry/aggregate";

const directory = new URL("../src/families/", import.meta.url);
const indexPath = fileURLToPath(new URL("index.ts", directory));

export function familyFiles(names: readonly string[]): string[] {
  return names
    .filter((name) => name.endsWith(".ts") && name !== "index.ts")
    .map((name) => name.slice(0, -".ts".length))
    .sort();
}

/** The export lines of an index file, order-insensitive: two PRs that each
 * append a line merge without conflict in any order. */
export function familyIndexLines(source: string): string[] {
  return source
    .split("\n")
    .filter((line) => line.startsWith("export { family as "))
    .sort();
}

export function renderFamilyIndex(ids: readonly string[]): string {
  const aliases = new Map<string, string>();
  const lines = ids.map((id) => {
    if (!FAMILY_ID.test(id))
      throw new Error(`Family file name must be kebab-case: ${id}.ts`);
    const alias = id.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase());
    const other = aliases.get(alias);
    if (other) throw new Error(`Families ${other} and ${id} share ${alias}`);
    aliases.set(alias, id);
    return `export { family as ${alias} } from "./${id}";`;
  });
  return [
    "// Generated by `npm run families:index`: one line per src/families/<id>.ts,",
    "// sorted by file name. Add a family by adding its descriptor and running the",
    "// script; tests/family-index.test.ts fails when this file is stale.",
    "export {};",
    ...lines,
    "",
  ].join("\n");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const args = process.argv.slice(2);
  if (args.length > 1 || (args.length === 1 && args[0] !== "--check"))
    throw new Error("Usage: npm run families:index [-- --check]");
  const expected = renderFamilyIndex(familyFiles(readdirSync(directory)));
  const current = readFileSync(indexPath, "utf8");
  if (args[0] === "--check") {
    if (
      JSON.stringify(familyIndexLines(current)) !==
      JSON.stringify(familyIndexLines(expected))
    ) {
      console.error(
        "src/families/index.ts is stale; run npm run families:index",
      );
      process.exit(1);
    }
  } else if (
    JSON.stringify(familyIndexLines(current)) !==
    JSON.stringify(familyIndexLines(expected))
  )
    writeFileSync(indexPath, expected);
}

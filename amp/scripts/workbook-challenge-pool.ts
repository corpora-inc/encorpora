/**
 * Builds the daily workbook's challenge pool (src/workbook/challenge-pool.ts):
 * printable assessment templates whose problems take several steps or
 * reasoning about a figure. Each template is scored from three generated
 * problems:
 *   shown work +3, several parts +2, plotting +2, a figure in every problem
 *   +1.5, half a point per explanation step (up to 6), a situation to read
 *   (a prompt over 110 characters) +1.
 * Kindergarten to grade 2 qualify at 3 with a figure, later grades at 4. Routine one-step
 * items that pass the score are listed in `routine` below and left out.
 *
 *   npx tsx scripts/workbook-challenge-pool.ts [--write]
 */
import { writeFileSync } from "node:fs";
import { skills } from "../src/curriculum/catalog";
import { templateRole } from "../src/learning/placement";
import { generateProblem, templates } from "../src/math/engine";
import { templateGrade } from "../src/server/mixed-practice";
import { paperExclusions } from "../src/workbook/paper-exclusions";

/** Routine items that score as rich (a picture and three short steps) but
 * are one familiar move: they are practice, not a challenge. */
const routine = new Set([
  "add-two-digit-regroup",
  "add-ones-regroup",
  "compare-groups",
  "compare-two-digit",
  "compare-weights",
  "hundreds-model",
  "make-ten-fact",
  "match-clock-five-minutes",
  "match-clock-half-hour",
  "minutes-past-hour",
  "numeral-for-quantity",
  "read-clock-five-minutes",
  "read-clock-hour-half",
  "subtract-whole-tens",
  "take-away-within-10",
  "count-sides-corners",
  "categorical-summary",
]);

const nodes = new Map(skills.map((s) => [s.id, s]));
const chosen: { id: string; grade: number; score: number }[] = [];
for (const t of templates) {
  if (!nodes.has(t.skillId) || paperExclusions.has(t.id)) continue;
  if (templateRole(t.id) !== "assessment" || routine.has(t.id)) continue;
  const problems = [0, 1, 2].map((i) =>
    generateProblem(t.id, `challenge-pool:${i}`),
  );
  const kind = problems[0]!.public.response.kind;
  const steps = Math.min(...problems.map((p) => p.explanation.length));
  const figure =
    problems.every((p) => !!p.public.figure) ||
    kind === "figure-choice" ||
    kind === "point-plot";
  const score =
    (kind === "structured-work" ? 3 : 0) +
    (kind === "multi-part-choice" ? 2 : 0) +
    (kind === "point-plot" ? 2 : 0) +
    (figure ? 1.5 : 0) +
    Math.min(steps, 6) / 2 +
    (problems[0]!.public.prompt.length > 110 ? 1 : 0);
  const grade = templateGrade(t, nodes);
  // Young learners reason from a picture: below grade 3 a challenge needs one.
  if (grade < 3 ? figure && score >= 3 : score >= 4)
    chosen.push({ id: t.id, grade, score });
}
chosen.sort((a, b) => a.grade - b.grade || a.id.localeCompare(b.id));
const byGrade = new Map<number, string[]>();
for (const c of chosen) {
  const g = Math.max(0, Math.floor(c.grade));
  byGrade.set(g, [...(byGrade.get(g) ?? []), c.id]);
}
for (const [g, ids] of byGrade) console.log(`grade ${g}: ${ids.length}`);
console.log(`${chosen.length} templates in the challenge pool`);
if (process.argv.includes("--write")) {
  const body = [...byGrade]
    .map(
      ([g, ids]) =>
        `  // ${g === 0 ? "Kindergarten" : `Grade ${g}`}\n${ids.map((id) => `  "${id}",`).join("\n")}`,
    )
    .join("\n");
  writeFileSync(
    new URL("../src/workbook/challenge-pool.ts", import.meta.url),
    `/** Templates that make a good Challenge on paper: several steps or a figure
 * to reason about, printable, and not a routine one-step item. Generated by
 * \`npx tsx scripts/workbook-challenge-pool.ts --write\`, which documents the
 * scoring; edit the script's \`routine\` list to curate, then regenerate. */
export const challengePool: ReadonlySet<string> = new Set<string>([
${body}
]);
`,
  );
}

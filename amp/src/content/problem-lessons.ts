/** One short lesson per problem type: what is given, what to find, how to
 * solve it, and a worked instance generated by the same template. */
export type ProblemLessonView = {
  templateId: string;
  title: string;
  goal: string;
  /** Plain-language meaning before the example; no unexplained notation. */
  intuition?: string;
  video?: LessonVideo;
  /** The named property or definition the method rests on. */
  principle: string | null;
  /** The method's terms with their glossary definitions; the same shape
   * every client has rendered since lessons began. */
  terms: { term: string; meaning: string }[];
  /** Every glossary entry the lesson's text and terms use, with the terms
   * their definitions use, for term cards and drill-down. */
  glossary: GlossaryCard[];
  /** How the lesson's texts link their words (`GlossaryLexicon`). */
  glossaryLexicon: GlossaryLexicon;
  method: string[];
  watch: string | null;
  example: {
    prompt: string;
    choices?: string[];
    figure?: SemanticFigure;
    /** Structured givens of the worked example (never the learner's own problem), for its animation. */
    givens?: RealNumberGivens;
    steps: string[];
    answer: string;
  };
};
export type ProblemMethod = {
  /** What the problem gives and what it asks for, in one sentence. */
  goal: string;
  /** Plain-language meaning before the example; no unexplained notation. */
  intuition?: string;
  /** Glossary terms the method uses (`src/glossary/`), each optionally with
   * a short note for this problem type. */
  terms?: MethodTerm[];
  /** The glossary entry an ambiguous word means in this method: lowercase
   * form → term id. */
  senses?: GlossarySenses;
  /** Glossary forms used as ordinary words in this method. */
  noLink?: string[];
  /** The steps that solve every instance of this problem type. */
  method: string[];
  /** The most common error, stated as what to do instead. */
  watch?: string;
};

const byId = new Map(
  [...templates, ...historicalTemplates].map((template) => [
    template.id,
    template,
  ]),
);
/** Lessons are served to every client that can receive the template, whatever
 * else it can draw, so the example is drawn for the oldest such client: a
 * newer scene component only when the template itself requires it. */
const lessonFigures = (template: TemplateMetadata) =>
  figureCapabilities.filter(
    (c) => c !== "scenes-v2" || template.requiredFigureCapability === c,
  );

export function hasProblemLesson(templateId: string) {
  return byId.has(templateId);
}

/** The example is another instance of the same template, never the problem the
 * learner is working on, so the lesson teaches the method without the answer. */
export function problemLesson(
  templateId: string,
  seed: string,
  avoidPrompt?: string,
  avoidResponse?: ProblemResponse,
  /** The learner's own instance: an example whose worked answer would also
   * answer it (one line written in another form) is never shown. */
  learnerProblem?: GeneratedProblem,
): ProblemLessonView {
  const template = byId.get(templateId);
  if (!template) throw new Error(`Unknown problem type ${templateId}`);
  const generateProblem = (id: string, exampleSeed: string) =>
    generateProblemFor(id, exampleSeed, lessonFigures(template));
  // The learner may see a newer figure surface than the example (which is
  // drawn for the oldest client); its legacy twin has the example's wording.
  const twinPrompt = learnerProblem
    ? generateProblem(templateId, learnerProblem.public.seed).public.prompt
    : undefined;
  let example = generateProblem(templateId, `${seed}:lesson:0`);
  const repeatsProblem = (p: typeof example) => {
    if (
      learnerProblem?.public.response.kind === "point-plot" &&
      learnerProblem.public.templateId === p.public.templateId &&
      gradeAnswer(learnerProblem, p.answer)
    )
      return true;
    // A figure choice is answered by one figure: an example whose correct
    // figure is the learner's (one line asked another way) shows the answer.
    if (
      learnerProblem?.public.response.kind === "figure-choice" &&
      p.public.response.kind === "figure-choice" &&
      answerText(p.public.response, p.answer) ===
        answerText(learnerProblem.public.response, learnerProblem.answer)
    )
      return true;
    // Structured work: the same givens asked in another mode (build, fill
    // or order) is the same problem, and the lesson would work it.
    if (
      learnerProblem?.public.response.kind === "structured-work" &&
      p.public.response.kind === "structured-work"
    )
      return workGivens(p) === workGivens(learnerProblem);
    if (p.public.prompt !== avoidPrompt && p.public.prompt !== twinPrompt)
      return false;
    // Multi-part items share their wording; their givens are the blank
    // labels and the figure. Rows and options are shuffled, so neither order
    // is compared.
    if (avoidResponse?.kind === "multi-part-choice") {
      const givens = (labels: string[], figure: unknown) =>
        JSON.stringify([[...labels].sort(), figure ?? null]);
      return (
        p.public.response.kind === "multi-part-choice" &&
        givens(
          p.public.response.blanks.map((blank) => blank.label),
          p.public.figure,
        ) ===
          givens(
            avoidResponse.blanks.map((blank) => blank.label),
            learnerProblem?.public.figure,
          )
      );
    }
    if (avoidResponse?.kind !== "multi-select") return true;
    return (
      p.public.response.kind === "multi-select" &&
      JSON.stringify(
        p.public.response.options.map((option) => option.label).sort(),
      ) ===
        JSON.stringify(
          avoidResponse.options.map((option) => option.label).sort(),
        )
    );
  };
  for (let i = 1; i < 8 && repeatsProblem(example); i++)
    example = generateProblem(templateId, `${seed}:lesson:${i}`);
  // A type whose figures carry a walkthrough in some frames shows one: the
  // example prefers an instance whose scene has steps to play.
  const walks = (p: typeof example) =>
    p.public.figure?.kind === "scene" && !!p.public.figure.scene.steps?.length;
  if (!walks(example))
    for (let i = 8; i < 24; i++) {
      const next = generateProblem(templateId, `${seed}:lesson:${i}`);
      if (walks(next) && !repeatsProblem(next)) {
        example = next;
        break;
      }
    }
  const response = example.public.response;
  const answer =
    response.kind === "choice" ||
    response.kind === "multi-select" ||
    response.kind === "point-plot" ||
    response.kind === "multi-part-choice" ||
    response.kind === "figure-choice" ||
    response.kind === "structured-work"
      ? answerText(response, example.answer)
      : skills.find((skill) => skill.id === template.skillId)?.strand ===
          "fractions"
        ? example.answer
        : displayAnswer(example.answer);
  const lessonTemplateId = templateReplacements[templateId] ?? templateId;
  const authored = methods[lessonTemplateId];
  const givens = realNumberGivens(templateId, example.public.seed);
  const reference = lessons.find((lesson) =>
    lesson.templateIds.includes(lessonTemplateId),
  );
  const candidateVideo = lessonVideoFor(templateId);
  // A fixed tutorial must not work the learner's current answer. A library
  // request has no active problem; practice supplies the server-owned instance.
  const video =
    candidateVideo &&
    (!avoidPrompt || learnerProblem) &&
    !candidateVideo.workedAnswers.some(
      (answer) => learnerProblem && gradeAnswer(learnerProblem, answer),
    )
      ? candidateVideo
      : undefined;
  const goal = authored?.goal ?? `${template.description}`;
  const intuition =
    authored?.intuition ??
    reference?.summary ??
    authored?.goal ??
    template.description;
  const principle = principles[lessonTemplateId] ?? null;
  const methodTerms = authored?.terms ?? [];
  // A hint names its own instance's numbers, so it is never a general method.
  const method = authored?.method ?? [template.description];
  const watch = authored?.watch ?? reference?.pitfalls[0] ?? null;
  const steps =
    response.kind === "figure-choice"
      ? example.explanation.filter(
          (step) => !step.startsWith(`${response.noun} `),
        )
      : example.explanation;
  const terms = methodTermDefinitions(methodTerms);
  const { glossary, glossaryLexicon } = glossaryPayload(
    [
      goal,
      intuition,
      ...method,
      watch ?? "",
      principle ?? "",
      ...terms.map((t) => t.meaning),
      ...steps,
    ],
    lessonGlossaryContext(lessonTemplateId, template),
    methodTerms.map(methodTermId),
  );
  return {
    templateId,
    ...(video ? { video } : {}),
    title: template.title,
    goal,
    intuition,
    principle,
    terms: terms.map(({ term, meaning }) => ({ term, meaning })),
    glossary,
    glossaryLexicon,
    method,
    watch,
    example: {
      prompt: example.public.prompt,
      ...(response.kind === "multi-select"
        ? { choices: response.options.map((option) => option.label) }
        : {}),
      // A private walkthrough of the example, when it has one, replaces its
      // problem figure: the lesson plays it revealed.
      ...(example.walkthrough
        ? { figure: { kind: "scene" as const, scene: example.walkthrough } }
        : example.public.figure
          ? { figure: example.public.figure }
          : {}),
      ...(givens ? { givens } : {}),
      // A lesson draws only the correct figure, so a step naming its card
      // ("Graph B is …") has nothing to point at; the answer line describes it.
      steps,
      answer,
    },
  };
}

/** How a problem type's lesson reads ambiguous words: its method's senses,
 * then its template's (generated hints and explanations). */
export function lessonGlossaryContext(
  templateId: string,
  template: TemplateMetadata | undefined = byId.get(templateId),
) {
  const method = methods[templateId];
  return {
    senses: { ...template?.glossarySenses, ...method?.senses },
    noLink: [...(template?.glossaryNoLink ?? []), ...(method?.noLink ?? [])],
  };
}

/** What a structured problem is about, independent of its mode: the line to
 * solve, the proof's goal and figure, or the values to find. */
function workGivens(p: GeneratedProblem): string {
  const g = p.workGrading;
  const r = p.public.response;
  if (!g || r.kind !== "structured-work") return p.public.prompt;
  if (g.mode === "derivation") return `derivation:${g.start}`;
  if (g.mode === "proof")
    return `proof:${r.goal}:${JSON.stringify(p.public.figure ?? null)}`;
  // Labeled values: the story without its mode sentence, and the labels.
  return `fields:${p.public.prompt.replace(/ (?:Enter each step|Some steps are filled in\. Enter the others)\.$/, "")}:${JSON.stringify(r.rows.map((row) => row.label ?? ""))}`;
}

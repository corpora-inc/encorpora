  token_hash text PRIMARY KEY,
  context jsonb NOT NULL,
  expires_at timestamptz NOT NULL,
  acquisition_journey_id uuid REFERENCES amp_ad_click_journeys(id) ON DELETE SET NULL,
  used_by text REFERENCES amp_auth_users(id) ON DELETE CASCADE

CREATE TABLE amp_parent_followups (
  user_id text PRIMARY KEY REFERENCES amp_auth_users(id) ON DELETE CASCADE,
  email text NOT NULL,
  program text CHECK (program IN ('ar-efa','az-esa')),
  campaign jsonb,
  acquisition_journey_id uuid REFERENCES amp_ad_click_journeys(id) ON DELETE SET NULL,
  verified_at timestamptz,
  newsletter boolean NOT NULL DEFAULT false,
  notice_version text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  unsubscribe_token text NOT NULL UNIQUE,
  unsubscribed_at timestamptz
);
CREATE TABLE amp_parent_followup_outbox (
  id uuid PRIMARY KEY,
  user_id text NOT NULL REFERENCES amp_parent_followups(user_id) ON DELETE CASCADE,
  stage text NOT NULL CHECK (stage IN ('welcome','reminder')),
  available_at timestamptz NOT NULL DEFAULT now(),
  first_dispatch_at timestamptz,
  lease_until timestamptz,
  lease_id uuid,
  attempts integer NOT NULL DEFAULT 0,
  payload jsonb,
  accepted_at timestamptz,
  receipt text,
  stopped_at timestamptz,
  stopped_reason text,
  UNIQUE(user_id,stage)
);

/**
 * The native wiring has four halves that only meet at runtime: the invokes in
 * native.ts, the grants in capabilities/default.json, the plugin registration
 * in src-tauri/src/lib.rs, and the commands each plugin actually exports. A
 * mismatch compiles clean and fails on a device with "not allowed" or
 * "command not found". These tests read all four and make them agree.
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { existsSync, readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { PRODUCT } from "../config.ts";

const app = (p: string) => fileURLToPath(new URL(`../../${p}`, import.meta.url));
const read = (p: string) => readFileSync(app(p), "utf8");
const PLUGIN_DIR: Record<string, string> = {
  tts: "../../corpan/plugins/tauri-plugin-tts",
  stt: "../../corpan/plugins/tauri-plugin-stt",
  "corpan-llm": "../../corpan/plugins/tauri-plugin-corpan-llm",
};

const native = read("src/lib/native.ts");
const invoked = [...native.matchAll(/"plugin:([a-z-]+)\|([a-z_]+)"/g)].map((m) => ({ plugin: m[1]!, cmd: m[2]! }));
const grants: string[] = JSON.parse(read("src-tauri/capabilities/default.json")).permissions;
const grantFor = ({ plugin, cmd }: { plugin: string; cmd: string }) => `${plugin}:allow-${cmd.replace(/_/g, "-")}`;

test("every invoked command is granted, and every grant is invoked", () => {
  assert.ok(invoked.length > 0);
  const wanted = new Set(invoked.map(grantFor));
  assert.deepEqual([...wanted].sort(), [...grants].sort());
  for (const g of grants) assert.doesNotMatch(g, /:default$/, `${g}: grant single commands, never a plugin default`);
});

test("every invoked command exists in its plugin", () => {
  for (const { plugin, cmd } of invoked) {
    const dir = PLUGIN_DIR[plugin];
    assert.ok(dir, `unknown plugin ${plugin}`);
    const build = read(`${dir}/build.rs`);
    const list = build.slice(build.indexOf("COMMANDS"), build.indexOf("];"));
    assert.ok(list.includes(`"${cmd}"`), `${plugin} does not export ${cmd}`);
    assert.ok(existsSync(app(`${dir}/permissions/autogenerated/commands/${cmd}.toml`)), `${plugin}:${cmd} has no permission`);
  }
});

test("every app command the frontend invokes is registered in the Rust shell", () => {
  const appCommands = [...native.matchAll(/invoke\("([a-z_]+)"/g)].map((m) => m[1]!);
  assert.ok(appCommands.includes("export_file"));
  const lib = read("src-tauri/src/lib.rs");
  const handler = lib.slice(lib.indexOf("generate_handler!["), lib.indexOf("])", lib.indexOf("generate_handler![")));
  for (const cmd of appCommands) assert.match(handler, new RegExp(`(^|[\\[\\s,:])${cmd}\\b`), `${cmd} is not registered`);
});

test("every invoked plugin is registered in the Rust shell and is a dependency", () => {
  const lib = read("src-tauri/src/lib.rs");
  const cargo = read("src-tauri/Cargo.toml");
  for (const plugin of new Set(invoked.map((i) => i.plugin))) {
    const crate = `tauri-plugin-${plugin}`;
    assert.ok(lib.includes(`.plugin(${crate.replace(/-/g, "_")}::init())`), `${crate} is not registered`);
    assert.match(cargo, new RegExp(`^${crate} = \\{ path = "\\.\\./\\.\\./\\.\\./corpan/plugins/${crate}" \\}`, "m"));
  }
});

/** Required (non-Option, no serde default) fields of a plugin args struct, camelCased. */
function requiredFields(plugin: string, struct: string): string[] {
  const src = read(`${PLUGIN_DIR[plugin]}/src/models.rs`);
  const start = src.indexOf(`pub struct ${struct} {`);
  assert.ok(start >= 0, `${struct} not found`);
  const body = src.slice(start, src.indexOf("\n}", start));
  const out: string[] = [];
  let defaulted = false;
  for (const line of body.split("\n").slice(1)) {
    if (/#\[serde\(default/.test(line)) defaulted = true;
    const m = line.match(/^\s*pub (\w+): (.+),\s*$/);
    if (!m) continue;
    if (!defaulted && !m[2]!.startsWith("Option<")) out.push(m[1]!.replace(/_([a-z])/g, (_, c: string) => c.toUpperCase()));
    defaulted = false;
  }
  return out;
}

/** Keys of the `args` object passed to one invoke in native.ts. */
function argKeys(cmd: string): string[] {
  const at = native.indexOf(`"plugin:${cmd}"`);
  assert.ok(at >= 0, `${cmd} is not invoked`);
  const m = native.slice(at, native.indexOf("\n", at)).match(/\{\s*args:\s*\{([^}]*)\}/);
  assert.ok(m, `${cmd} must pass { args: {...} }`);
  return m[1]!.split(",").map((s) => s.split(":")[0]!.trim()).filter(Boolean);
}

test("plugin payloads carry every field the Rust side requires", () => {
  const cases: [string, string, string][] = [
    ["tts|speak", "tts", "SpeakArgs"],
    ["stt|prepare", "stt", "PrepareArgs"],
    ["stt|start_session", "stt", "StartSessionArgs"],
    ["stt|stop_session", "stt", "StopSessionArgs"],
  ];
  for (const [cmd, plugin, struct] of cases) {
    const keys = argKeys(cmd);
    for (const f of requiredFields(plugin, struct)) assert.ok(keys.includes(f), `${cmd} is missing ${f} (has ${keys.join(", ")})`);
  }
});

test("the shell names the product from config.ts and keeps its own [patch]", () => {
  const conf = JSON.parse(read("src-tauri/tauri.conf.json"));
  assert.equal(conf.productName, PRODUCT.name);
  assert.equal(conf.app.windows[0].title, PRODUCT.name);
  assert.equal(conf.identifier, PRODUCT.bundleId);
  // ADR-0011: the llama.cpp fork is honoured only from this app's own root manifest.
  const cargo = read("src-tauri/Cargo.toml");
  const patch = cargo.match(/^llama-cpp-sys-2 = \{ path = "([^"]+)" \}/m);
  assert.ok(patch, "llama-cpp-sys-2 [patch] missing");
  assert.ok(existsSync(app(`src-tauri/${patch[1]}/Cargo.toml`)), "patched llama-cpp-sys-2 path does not exist");
  assert.doesNotMatch(cargo, /^\[workspace\]/m);
  // CI's bare `cargo check --target aarch64-apple-ios` compiles plugin Swift for this iOS version.
  const ci = read("../../.github/workflows/ci.yml");
  assert.ok(ci.includes(`IPHONEOS_DEPLOYMENT_TARGET: "${conf.bundle.iOS.minimumSystemVersion}"`), "CI iOS deployment target differs from tauri.conf.json");
});

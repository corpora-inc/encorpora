def main():
    seed_path = pathlib.Path(__file__).parent / "seed" / "words_seed.json"
    rows = json.loads(seed_path.read_text())

    # Words use compact one-line-per-row formatting. We preserve that by
    # parsing + serializing each row, then joining with line endings —
    # `json.dumps` defaults would re-pretty-print the whole file.
    updated_rows = []
    for row in rows:
        wid = row["id"]
        existing = dict(row.get("meaning") or {})
        extra = T.get(wid, {})
        for lang, gloss in extra.items():
            if lang in existing:
                continue
            existing[lang] = gloss
        row["meaning"] = existing
        updated_rows.append(row)

    # One-line-per-entry, ordered keys preserved by Python 3.7+ dict.
    out_lines = ["["]
    for i, row in enumerate(updated_rows):
        suffix = "," if i < len(updated_rows) - 1 else ""
        out_lines.append("  " + json.dumps(row, ensure_ascii=False) + suffix)
    out_lines.append("]")
    seed_path.write_text("\n".join(out_lines) + "\n")
    print(f"Wrote {len(updated_rows)} rows, each with up to {len(next(iter(T.values())))} language glosses, to {seed_path.name}")


if __name__ == "__main__":
    main()

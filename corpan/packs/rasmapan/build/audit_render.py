#!/usr/bin/env python3
"""Raster-based audit of stroke-order medians.

The previous SVG-based audit (`audit_strokes.py`) was generated by
the same Python that builds the medians — so build bugs hid behind
audit bugs. This audit goes through a separate path:

1. **Pillow** rasterizes each Amiri glyph polygon to a binary mask
   (the "visible letter" — exactly the shape the user sees on screen
   filled in sepia).
2. The masked Calliar median (writer.medians) is drawn on top with a
   line of the same effective thickness as the runtime pen tip
   (4 CSS px at ≈ 600px canvas height ≈ 12 device px = ~8 mask px at
   600x600).
3. We compute two quality metrics PER LETTER:
   - **coverage**: fraction of pen-trail pixels that fall INSIDE the
     glyph silhouette. 1.0 means the pen tip never leaves the visible
     letter. < 0.85 = the animation visibly extends outside the
     glyph.
   - **stroke_span**: the median's bbox area as a fraction of the
     outline bbox area. < 0.3 = the pen tip traces only a fragment of
     the letter (the kaaf/yaa failure mode).
4. Output: one PNG per letter to `build/render_audit/<id>.png` plus
   a 28-letter grid `build/render_audit/_grid.png`. The PNG renders
   match what the user sees on device EXCEPT for the timing animation
   — the PNG shows the COMPLETED stroke trail. A flag list prints to
   stdout so problem letters are surfaced before reload.

Why this is better than the SVG audit:
- The mask is a PIL binary image computed from the polygon — not the
  polygon itself. If the SVG renderer interprets the polygon
  differently than PIL, this audit would catch it (the original
  audit couldn't).
- The pen-trail / outline intersection is a pixel-perfect test, not
  a "does the line look right" eyeball.
- The numeric metrics flag letters needing review without subjective
  judgement.
"""
from __future__ import annotations

import json
import math
import pathlib
import sqlite3
import sys
from typing import Dict, List, Optional, Tuple

from PIL import Image, ImageDraw, ImageFont

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from build_arabic_pack import AmiriExtractor  # noqa: E402

DB = HERE.parent / "data" / "arabic.sqlite3"
TTF = HERE / "vendor" / "Amiri-Regular.ttf"
OUT_DIR = HERE / "render_audit"
OUT_DIR.mkdir(exist_ok=True)
LETTERS_SEED = HERE / "seed" / "letters_seed.json"

VIEWBOX = 1000.0
CANVAS = 600  # px per letter card
PAD = 40
INNER = CANVAS - 2 * PAD


def vb_to_px(x: float, y: float) -> Tuple[float, float]:
    return (
        PAD + x * (INNER / VIEWBOX),
        PAD + y * (INNER / VIEWBOX),
    )


def parse_svg_path_to_polygon(d: str) -> List[Tuple[float, float]]:
    """Extract the (M, L) point sequence from a transformed SVG path.
    The AmiriExtractor's pipeline already pre-flattens curves to
    line segments, so paths are M x y L x y L x y ... Z. This is a
    safe minimal parser for our specific output."""
    pts: List[Tuple[float, float]] = []
    tokens = d.replace(",", " ").split()
    i = 0
    cur_x = 0.0
    cur_y = 0.0
    while i < len(tokens):
        cmd = tokens[i]
        if cmd in ("M", "L"):
            i += 1
            cur_x = float(tokens[i])
            i += 1
            cur_y = float(tokens[i])
            i += 1
            pts.append((cur_x, cur_y))
        elif cmd in ("m", "l"):
            i += 1
            dx = float(tokens[i])
            i += 1
            dy = float(tokens[i])
            i += 1
            cur_x += dx
            cur_y += dy
            pts.append((cur_x, cur_y))
        elif cmd in ("Z", "z"):
            i += 1
        elif cmd in ("H",):
            i += 1
            cur_x = float(tokens[i])
            i += 1
            pts.append((cur_x, cur_y))
        elif cmd in ("V",):
            i += 1
            cur_y = float(tokens[i])
            i += 1
            pts.append((cur_x, cur_y))
        else:
            # Try parsing as a bare number — implicit L continuation
            try:
                cur_x = float(tokens[i])
                i += 1
                cur_y = float(tokens[i])
                i += 1
                pts.append((cur_x, cur_y))
            except (ValueError, IndexError):
                i += 1
    return pts


def render_letter(
    family_id: str,
    polygons: List[List[List[float]]],
    medians: List[List[List[float]]],
) -> Tuple[Image.Image, float, float]:
    """Returns (canvas_image, coverage, stroke_span)."""
    img = Image.new("RGB", (CANVAS, CANVAS), color=(251, 246, 236))  # parchment
    draw = ImageDraw.Draw(img)

    # 1) Render the glyph as a filled silhouette (the "ghost"). Polygons
    #    are pre-flattened (FlattenPen-derived) so we don't need to
    #    interpret SVG curve commands.
    mask = Image.new("L", (CANVAS, CANVAS), 0)
    mask_draw = ImageDraw.Draw(mask)
    for poly in polygons:
        if len(poly) < 3:
            continue
        px_pts = [vb_to_px(p[0], p[1]) for p in poly]
        mask_draw.polygon(px_pts, fill=255)
    # Composite ghost onto canvas (light sepia at low alpha).
    ghost = Image.new("RGB", (CANVAS, CANVAS), color=(220, 207, 184))
    img.paste(ghost, mask=mask)

    # 2) Render the pen trail.
    trail = Image.new("L", (CANVAS, CANVAS), 0)
    trail_draw = ImageDraw.Draw(trail)
    PEN_W = 12  # ~4 CSS px at canvas height 600
    for stroke in medians:
        if len(stroke) == 1:
            x, y = vb_to_px(stroke[0][0], stroke[0][1])
            trail_draw.ellipse(
                [x - PEN_W / 2, y - PEN_W / 2, x + PEN_W / 2, y + PEN_W / 2],
                fill=255,
            )
            continue
        px = [vb_to_px(p[0], p[1]) for p in stroke]
        trail_draw.line(px, fill=255, width=PEN_W, joint="curve")
        # Round caps (PIL line doesn't do them by default at the
        # endpoints).
        for x, y in (px[0], px[-1]):
            trail_draw.ellipse(
                [x - PEN_W / 2, y - PEN_W / 2, x + PEN_W / 2, y + PEN_W / 2],
                fill=255,
            )
    # Composite pen trail onto canvas (sepia ink).
    ink = Image.new("RGB", (CANVAS, CANVAS), color=(139, 105, 20))
    img.paste(ink, mask=trail)

    # 3) Start dot (green circle) at first point of first stroke.
    if medians and medians[0]:
        sx, sy = vb_to_px(medians[0][0][0], medians[0][0][1])
        r = 14
        draw.ellipse(
            [sx - r, sy - r, sx + r, sy + r],
            outline=(46, 125, 50),
            width=3,
        )

    # 4) End dot (red filled) at last point of last stroke.
    if medians and medians[-1]:
        last = medians[-1][-1]
        ex, ey = vb_to_px(last[0], last[1])
        r = 8
        draw.ellipse(
            [ex - r, ey - r, ex + r, ey + r],
            fill=(139, 60, 30),
        )

    # Label
    try:
        font = ImageFont.truetype("/System/Library/Fonts/Supplemental/Georgia.ttf", 28)
    except OSError:
        font = ImageFont.load_default()
    draw.text((PAD, 8), family_id, fill=(60, 40, 20), font=font)

    # Quality metrics
    # coverage = pen-trail pixels inside glyph silhouette / total
    # pen-trail pixels.
    import numpy as np
    mask_arr = np.array(mask)
    trail_arr = np.array(trail)
    trail_total = int((trail_arr > 0).sum())
    if trail_total == 0:
        coverage = 0.0
    else:
        inside = int(((trail_arr > 0) & (mask_arr > 0)).sum())
        coverage = inside / trail_total

    # stroke_span = pen trail bbox area / glyph bbox area.
    if medians and medians[0]:
        ys = [p[1] for s in medians for p in s]
        xs = [p[0] for s in medians for p in s]
        med_area = max(1.0, (max(xs) - min(xs))) * max(1.0, (max(ys) - min(ys)))
    else:
        med_area = 0.0
    all_outline_pts: List[Tuple[float, float]] = []
    for poly in polygons:
        all_outline_pts.extend([(p[0], p[1]) for p in poly])
    if all_outline_pts:
        oxs = [p[0] for p in all_outline_pts]
        oys = [p[1] for p in all_outline_pts]
        o_area = max(1.0, (max(oxs) - min(oxs))) * max(1.0, (max(oys) - min(oys)))
        stroke_span = med_area / o_area
    else:
        stroke_span = 0.0

    return img, coverage, stroke_span


def main() -> None:
    if not DB.exists():
        print(f"Missing {DB}", file=sys.stderr)
        sys.exit(1)
    if not TTF.exists():
        print(f"Missing {TTF}", file=sys.stderr)
        sys.exit(1)

    # Load medians from the built DB; load polygons fresh from the font
    # so we audit against the same geometry the runtime uses.
    extractor = AmiriExtractor(TTF)
    letters_seed = json.loads(LETTERS_SEED.read_text())
    family_to_cp: Dict[str, int] = {}
    for entry in letters_seed:
        fam = entry.get("id")
        cp_hex = (entry.get("positions") or {}).get("isolated")
        if fam and cp_hex:
            try:
                family_to_cp[fam] = int(cp_hex, 16)
            except ValueError:
                continue

    with sqlite3.connect(str(DB)) as cx:
        cur = cx.execute(
            "SELECT id, data_json FROM arabic_letter_writer "
            "WHERE id NOT LIKE '%.%' ORDER BY id"
        )
        rows = [(wid, json.loads(blob)) for wid, blob in cur]

    cards: List[Tuple[str, Image.Image, float, float]] = []
    print(f"{'family':<10} {'cover':>6} {'span':>6}  {'scoring':<8}  flags")
    print("-" * 70)
    for wid, data in rows:
        medians = data.get("medians") or []
        scoring = data.get("scoring") or "outline"
        cp = family_to_cp.get(wid)
        if cp is None:
            print(f"{wid:<10}    n/a    n/a  {scoring:<8}  no-codepoint")
            continue
        glyph_data = extractor.extract(cp)
        if not glyph_data or not glyph_data.polygons:
            print(f"{wid:<10}    n/a    n/a  {scoring:<8}  no-polygons")
            continue
        img, cov, span = render_letter(wid, glyph_data.polygons, medians)
        # Case-insensitive filesystems (macOS HFS+) collapse "Taa" /
        # "taa" to the same file; tag capitalized ids with a suffix
        # so the audit shows both letters.
        suffix = "_emphatic" if wid[0].isupper() else ""
        img.save(OUT_DIR / f"{wid.lower()}{suffix}.png")
        flags = []
        if scoring != "median":
            flags.append("no-animation")
        if cov < 0.85:
            flags.append(f"pen-outside-outline(cov={cov:.2f})")
        if span < 0.30:
            flags.append(f"only-fragment-traced(span={span:.2f})")
        flag_str = " ".join(flags) if flags else "OK"
        print(f"{wid:<10} {cov:>6.2f} {span:>6.2f}  {scoring:<8}  {flag_str}")
        cards.append((wid, img, cov, span))

    # Build a 7×4 grid PNG.
    cols = 7
    rows_n = (len(cards) + cols - 1) // cols
    cw = CANVAS
    ch = CANVAS
    grid = Image.new("RGB", (cols * cw, rows_n * ch), color=(251, 246, 236))
    for i, (_wid, img, _c, _s) in enumerate(cards):
        x = (i % cols) * cw
        y = (i // cols) * ch
        grid.paste(img, (x, y))
    grid.save(OUT_DIR / "_grid.png")
    print(f"\nWrote {len(cards)} PNGs + grid to {OUT_DIR}")


if __name__ == "__main__":
    main()

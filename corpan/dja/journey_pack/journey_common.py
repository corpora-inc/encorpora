def unit_id_re(target: str) -> re.Pattern:
    """V-15 unit-id grammar for an underscore-canonical target subtag."""
    return re.compile(
        rf"^{re.escape(target)}\.(a0|a1|a2|b1|b2|c1|c2)\.u\d{{2}}$"
    )


def arc_id_re(target: str) -> re.Pattern:
    return re.compile(rf"^{re.escape(target)}\.arc\d+$")


def underscore_lang(code: str) -> str:
    """Hyphens→underscores, lowercase — the installer-canonical subtag form."""
    return code.lower().replace("-", "_")


def nfc_len(text: str) -> int:
    """NFC code-point length (items.text_len, course-pack.md §2)."""
    return len(unicodedata.normalize("NFC", text))



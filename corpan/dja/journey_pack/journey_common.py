# ---------------------------------------------------------------------------
# ItemRef — canonical serialization (course-pack.md §1 / contract R2).
# Python mirror of itemRefKey()/parseItemRef() in activityContract.ts.
# kind and source never contain ":"; id may — parse on the FIRST TWO colons.
# ---------------------------------------------------------------------------

ITEM_KINDS = (
    "phrase", "word", "char", "segment", "grammarNode", "phoneme", "concept",
)


@dataclass(frozen=True)
class ItemRef:
    kind: str
    source: str
    id: str


def item_ref_key(ref: ItemRef) -> str:
    return f"{ref.kind}:{ref.source}:{ref.id}"


def parse_item_ref(s: str) -> Optional[ItemRef]:
    i = s.find(":")
    if i < 0:
        return None
    j = s.find(":", i + 1)
    if j < 0:
        return None
    return ItemRef(kind=s[:i], source=s[i + 1:j], id=s[j + 1:])


# ---------------------------------------------------------------------------
# ACTIVITY_TYPES — read from the synced contract copy (R4). We PARSE the
# generated TypeScript rather than keeping a second hand-written list, so the
# Python pipeline can never drift from the contract: sync-contract.mjs --check
# already gates the TS copies, and we read one of those synced copies.
# ---------------------------------------------------------------------------

_ACTIVITY_TYPES_RE = re.compile(
    r"export\s+const\s+ACTIVITY_TYPES\s*=\s*\{(.*?)\n\}", re.S,
)
_ACTIVITY_ROW_RE = re.compile(r"^\s*([a-z][a-z0-9_]*)\s*:\s*\{", re.M)


def load_activity_types(contract_path: Path = SYNCED_CONTRACT) -> List[str]:
    """Keys of the ACTIVITY_TYPES registry, from the synced contract copy."""
    if not contract_path.exists():
        raise FileNotFoundError(
            f"synced activity contract not found at {contract_path} — "
            "run `node packs/sdk/sync-contract.mjs` from the corpan repo root"
        )
    src = contract_path.read_text(encoding="utf-8")
    m = _ACTIVITY_TYPES_RE.search(src)
    if not m:
        raise ValueError(
            f"could not locate `export const ACTIVITY_TYPES` in {contract_path}"
        )
    keys = _ACTIVITY_ROW_RE.findall(m.group(1))
    if not keys:
        raise ValueError(
            f"ACTIVITY_TYPES block in {contract_path} parsed to zero entries"
        )
    return keys


